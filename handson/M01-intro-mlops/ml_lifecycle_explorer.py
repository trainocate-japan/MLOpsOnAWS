# ML ライフサイクル（反復的なプロセス）
ML_LIFECYCLE = [
    ("ビジネス上の問題のフレーム化", "KPI・成功基準・予算を定義する。ML が適切か判断する。"),
    ("データ収集と準備", "データソースを特定し、クリーニング・分割する。"),
    ("特徴量エンジニアリング", "生データから予測に有効な特徴量を作る。"),
    ("モデルトレーニングとチューニング", "アルゴリズムを選択し、ハイパーパラメータを調整する。"),
    ("モデル評価", "検証データで精度・バイアス・説明可能性を確認する。"),
    ("デプロイ", "モデルを推論エンドポイントやバッチ処理として公開する。"),
    ("モニタリング", "本番の予測品質・データドリフトを監視し、再学習を判断する。"),
]

# MLOps 成熟度モデル（4 レベル）
MATURITY_LEVELS = {
    "Initial": {
        "コラボレーション": "分断されたデータサイエンスチームと IT チーム",
        "データ処理": "1 回限りのデータ収集と準備",
        "トレーニング": "手動でのトレーニングと再トレーニング",
        "デプロイ": "手動・一貫性なし",
    },
    "Repeatable": {
        "コラボレーション": "利害関係者との連携向上・共有プロジェクト目標",
        "データ処理": "定義済みデータ戦略・自動データパイプライン",
        "トレーニング": "自動化されたモデルビルドパイプライン",
        "デプロイ": "手動でのモデル検証",
    },
    "Reliable": {
        "コラボレーション": "クロスファンクショナルなプロジェクトチーム",
        "データ処理": "データガバナンス・統合された ML パイプライン",
        "トレーニング": "自動検証・CI/CD",
        "デプロイ": "自動化された ML CI パイプライン",
    },
    "Scalable": {
        "コラボレーション": "ベストプラクティスの全社共有・透明性",
        "データ処理": "セルフサービスと再利用可能なパターン",
        "トレーニング": "完全自動化",
        "デプロイ": "ダッシュボードと自動再学習",
    },
}


def print_lifecycle():
    print("=" * 66)
    print(" ML ライフサイクル（反復的なプロセス）")
    print("=" * 66)
    for i, (phase, desc) in enumerate(ML_LIFECYCLE, 1):
        print(f"\n{i}. {phase}")
        print(f"   {desc}")
    print("\n→ MLOps はこのライフサイクル全体を自動化・標準化し、"
          "本番で運用し続けることを目指します。")


def print_maturity():
    print("\n" + "=" * 66)
    print(" MLOps 成熟度モデル（Initial → Repeatable → Reliable → Scalable）")
    print("=" * 66)
    for level, attrs in MATURITY_LEVELS.items():
        print(f"\n【{level}】")
        for k, v in attrs.items():
            print(f"  - {k}: {v}")


def self_assessment():
    print("\n" + "=" * 66)
    print(" セルフアセスメント（考えてみましょう）")
    print("=" * 66)
    questions = [
        "データの収集・準備は自動化されていますか？（Initial→Repeatable の分かれ目）",
        "モデルのビルドはパイプライン化されていますか？",
        "デプロイ前に自動検証と CI/CD がありますか？（Reliable の条件）",
        "本番のドリフトを検知し、自動で再学習できますか？（Scalable の条件）",
        "組織全体でベストプラクティスとテンプレートを共有していますか？",
    ]
    for q in questions:
        print(f"  □ {q}")
    print("\n→ 「いいえ」が多いフェーズが、次に取り組むべき改善ポイントです。")


def main():
    print_lifecycle()
    print_maturity()
    self_assessment()
    print("\nポイント: MLOps は ML モデルそのものよりも、"
          "その周りのプロセス・人・テクノロジーの統合が重要です。")


if __name__ == "__main__":
    main()
