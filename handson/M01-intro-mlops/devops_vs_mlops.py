"""
モジュール 1: DevOps と MLOps の比較
------------------------------------
このスクリプトは AWS リソースを作成しません。
「プログラマーがソフトウェアのコードを書き、データが ML のモデルを書く」という
考え方をもとに、DevOps と MLOps の共通点と相違点を整理します。

実行:
    python devops_vs_mlops.py
"""

# DevOps と MLOps の比較（スライド「DevOps の概念を MLOps に適用する」対応）
COMPARISON = [
    # (観点, DevOps, MLOps)
    ("主な成果物", "コード", "コード + データ + モデル"),
    ("バージョン管理", "ソースコード", "コード・データ・モデル・特徴量・ハイパーパラメータ"),
    ("ビルド", "コンパイル・パッケージング", "データ処理 + モデルトレーニング"),
    ("テスト", "単体・結合・E2E テスト", "左記に加えモデル評価・バイアス・説明可能性"),
    ("CI/CD", "コードのビルド・デプロイ自動化", "データ・モデル・コードの自動パッケージ化とデプロイ"),
    ("モニタリング", "アプリのメトリクス・ログ", "左記に加えデータドリフト・モデル精度の劣化"),
    ("再デプロイの契機", "コード変更", "コード変更 + データ変化 + 精度劣化（再学習）"),
]

# MLOps 特有の考慮事項（スライド「ML の実装に関する考慮事項」対応）
ML_CONSIDERATIONS = [
    ("一貫性", "同じ入力・環境で同じ結果が得られる"),
    ("柔軟性", "フレームワーク・アルゴリズムを切り替えられる"),
    ("再現性", "過去の実験・モデルを再現できる（データ・コード・環境のバージョン管理）"),
    ("スケーラビリティ", "需要に応じてトレーニング・推論をスケールできる"),
    ("監査可能性", "誰がいつ何を変更したか追跡できる"),
    ("説明可能性", "モデルがなぜその予測をしたか説明できる"),
]


def print_comparison():
    print("=" * 78)
    print(" DevOps と MLOps の比較")
    print("=" * 78)
    print(f"\n{'観点':<16}{'DevOps':<26}{'MLOps'}")
    print("-" * 78)
    for aspect, devops, mlops in COMPARISON:
        print(f"{aspect:<16}{devops:<26}{mlops}")
    print("\n→ MLOps は DevOps を土台に、データとモデルという新しい対象を加えたものです。")


def print_considerations():
    print("\n" + "=" * 78)
    print(" ML 実装の考慮事項（MLOps が満たすべき性質）")
    print("=" * 78)
    for name, desc in ML_CONSIDERATIONS:
        print(f"  - {name}: {desc}")


def print_roles():
    print("\n" + "=" * 78)
    print(" MLOps に関わる代表的なロール（ピープル）")
    print("=" * 78)
    roles = [
        ("DevOps エンジニア", "パイプライン・インフラ・CI/CD の自動化"),
        ("データエンジニア", "データ収集・変換・パイプラインの構築"),
        ("データサイエンティスト", "特徴量エンジニアリング・モデル開発・評価"),
        ("MLOps エンジニア", "実験から本番までの運用化・監視・再学習の仕組み化"),
        ("モデル承認者", "本番デプロイ前のモデル承認"),
        ("ガバナンス責任者", "コンプライアンス・監査・リスク管理"),
    ]
    for role, resp in roles:
        print(f"  - {role}: {resp}")
    print("\n→ MLOps の成功にはこれらのロール間のスムーズなコミュニケーションが不可欠です。")


def main():
    print_comparison()
    print_considerations()
    print_roles()


if __name__ == "__main__":
    main()
