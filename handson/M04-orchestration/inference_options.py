def print_options():
    banner("SageMaker AI の推論オプション")
    for name, attrs in OPTIONS.items():
        print(f"\n【{name}】")
        for k, v in attrs.items():
            print(f"  {k}: {v}")


def decision_flow():
    print("\n" + "=" * 66)
    print(" 推論オプションの選択フロー（スライド対応）")
    print("=" * 66)
    print("""
  1. 大規模なデータセット全体から推論を得たい？
        Yes → バッチ変換
  2. キューイングのメリットがある？（処理時間が長い・ペイロードが大きい）
        Yes → 非同期推論
  3. トラフィックが断続的で、コールドスタートを許容できる？
        Yes → サーバーレス推論
  4. 低レイテンシーの常時稼働が必要？
        Yes → リアルタイム推論
""")
    print("ナレッジチェック: 処理時間が短く、非アクティブが続き、コールドスタートに")
    print("耐えられる → サーバーレス推論")


def main():
    print_options()
    decision_flow()


if __name__ == "__main__":
    main()
